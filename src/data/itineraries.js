// Generic day generator for any destination when customized
export function buildCustomItinerary(destinationName, days = 5, profile = 'Conforto') {
  const normalizedKey = destinationName?.toLowerCase().includes('gramado') ? 'gramado' :
                        destinationName?.toLowerCase().includes('noronha') ? 'noronha' : null;

  if (normalizedKey && ITINERARIES_DATA[normalizedKey]) {
    const baseList = ITINERARIES_DATA[normalizedKey];
    if (days <= baseList.length) {
      return baseList.slice(0, days);
    }
    // If user requested more days than base, extend naturally
    const extended = [...baseList];
    for (let d = baseList.length + 1; d <= days; d++) {
      extended.push({
        day: d,
        theme: `Exploração Livre & Experiências Exclusivas em ${destinationName}`,
        morning: {
          title: 'Manhã de Bem-Estar e Mirantes Especiais',
          activity: `Passeio tranquilo pelos recantos menos explorados de ${destinationName}, com café da manhã reforçado e contemplação de paisagens naturais.`,
          tip: 'Aproveite a luz da manhã para fotografias sem multidões.'
        },
        afternoon: {
          title: 'Experiência Cultural & Gastronomia Típica',
          activity: `Visita a feiras de artesanato, ateliês de produtores locais e almoço com foco no perfil ${profile}.`,
          tip: 'Converse com os artesãos e produtores locais para dicas genuínas da região.'
        },
        evening: {
          title: 'Jantar Harmonizado de Despedida',
          activity: `Experiência sensorial em restaurante de alta gastronomia com ingredientes típicos e carta de vinhos selecionada.`,
          tip: 'Faça um brinde celebrando os momentos mais marcantes da jornada.'
        }
      });
    }
    return extended;
  }

  // Fallback procedural generator for Paris, Rio, Lisboa, Lençóis, Kyoto, etc.
  const genericDays = [];
  const dayThemes = [
    'Chegada & Primeiro Contato com a Atmosfera Local',
    'Marcos Históricos & Cenários Cartão-Postal',
    'Imersão Cultural, Museus e Gastronomia de Raiz',
    'Belezas Naturais & Mirantes com Pôr do Sol',
    'Passeios Exclusivos & Vilas do Entorno',
    'Feiras Tradicionais, Compras & Design Local',
    'Dia de Relaxamento, Spa & Celebração'
  ];

  for (let i = 1; i <= days; i++) {
    const themeIdx = (i - 1) % dayThemes.length;
    genericDays.push({
      day: i,
      theme: `${dayThemes[themeIdx]} — ${destinationName}`,
      morning: {
        title: `Manhã: Exploração Icônica e Café da Manhã Tradicional`,
        activity: `Despertar com café artesanal e visita guiada aos pontos mais emblemáticos de ${destinationName} com acesso prioritário.`,
        tip: 'Inicie o dia cedo para vivenciar os monumentos com tranquilidade.'
      },
      afternoon: {
        title: `Tarde: Almoço de Alta Gastronomia & Passeio Guiado`,
        activity: `Degustação da culinária típica da região em restaurante renomado, seguido de caminhada contemplativa pelos bairros mais charmosos.`,
        tip: 'Leve calçados confortáveis e hidrate-se durante as caminhadas.'
      },
      evening: {
        title: `Noite: Experiência Enogastronômica e Vistas Noturnas`,
        activity: `Jantar intimista com menu degustação ou bar com música ao vivo e coquetelaria autoral com vista deslumbrante da cidade.`,
        tip: 'Consulte a programação cultural da noite para apresentações locais.'
      }
    });
  }

  return genericDays;
}
